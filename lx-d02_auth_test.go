package thermoprint

import (
	"bytes"
	"testing"
)

// Captured from a real LX-D02 (MAC c0:00:00:00:01:88).
func TestHandshakeCRC(t *testing.T) {
	challenge := []byte{0xb5, 0x7c, 0x4c, 0xb8, 0xae, 0x70, 0x51, 0xe6, 0xd3, 0x06}
	mac := []byte{0xc0, 0x00, 0x00, 0x00, 0x01, 0x88}
	low, high := handshakeCRC(challenge, mac)
	if want := []byte{0x52, 0x8b, 0x06, 0x58, 0x06, 0xe0, 0x77, 0x47, 0x6d, 0xa4}; !bytes.Equal(low, want) {
		t.Errorf("low = % x, want % x", low, want)
	}
	if want := []byte{0x16, 0x4b, 0x12, 0xfc, 0x6a, 0x19, 0xcf, 0x24, 0x04, 0x3c}; !bytes.Equal(high, want) {
		t.Errorf("high = % x, want % x", high, want)
	}
}
